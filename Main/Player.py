class Player :
    def __init__(self):
        self.Name = ""
        self.Class = None
        self.Level = 1
        self.Integrity = 0
        self.Defense = 0
        self.Regen = 0


    def Name(self) :
        return self.Name
      
    def Class (self):
        return self.Class
    
    def Level (self):
        return self.Level
    
